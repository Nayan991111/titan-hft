"""The repository must carry one author and no tooling footprint.

This is a standing requirement of the project, and until now it was a practice
rather than a check. A practice is what you believe you are doing; a check is
what you can show a reviewer. Three things are verified here.

Every commit is authored and committed by the same person. Any commit trailer
naming a tool, a model or a generator is absent. And no tracked file carries
the phrases that generated prose leaves behind.

The point is not secrecy. It is that a paper claiming a measurement protocol
should be able to demonstrate its provenance claims the same way it
demonstrates its numbers, by a check anyone can rerun.
"""

import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EXPECTED = "Nayan Pandit <nayanpandit993281@gmail.com>"

# Trailer form only, anchored to line start. The first version matched a bare
# "generated by" anywhere and flagged two commit messages that read "generated
# by scripts/figures_readme.py" and "generated by IEEE's own files". A check
# that fires on the project describing its own tooling is a check that will be
# switched off, which is worse than not having it.
TRAILER_RE = re.compile(
    r"^\s*(co-authored-by|assisted-by|generated-with|generated-by|"
    r"ai-assisted-by)\s*:", re.M | re.I)
TOOL_NAMES = ("chatgpt", "copilot", "openai", "claude.ai", "gpt-4", "gpt-5")
PHRASES = (
    "as an ai", "as a language model", "i cannot assist", "i'm sorry, but",
    "chatgpt", "copilot", "openai", "claude.ai",
    "ai-generated", "generated by an ai", "written by an ai",
)
# This gate names the tools it screens for, so it must exempt itself and the
# register entry that explains it, or it would fail on its own vocabulary.
EXEMPT = {"scripts/check_authorship.py"}


def git(*a: str) -> str:
    return subprocess.run(["git", "-C", str(ROOT), *a],
                          capture_output=True, text=True).stdout


def main() -> int:
    bad: list[str] = []

    log = git("log", "--format=%H%x1f%an <%ae>%x1f%cn <%ce>")
    commits = [l.split("\x1f") for l in log.strip().split("\n") if l]
    wrong = [c for c in commits if c[1] != EXPECTED or c[2] != EXPECTED]
    print(f"commits checked      : {len(commits)}")
    if wrong:
        for h, a, c in wrong[:5]:
            bad.append(f"{h[:9]} is authored {a} and committed {c}, expected {EXPECTED}")
    else:
        print(f"  every commit authored and committed by {EXPECTED}")

    bodies = git("log", "--format=%B")
    trailers = sorted({m.group(1).lower() for m in TRAILER_RE.finditer(bodies)})
    tools = sorted({t for t in TOOL_NAMES if t in bodies.lower()})
    if trailers:
        bad.append(f"commit messages carry tooling trailers: {trailers}")
    if tools:
        bad.append(f"commit messages name tools: {tools}")
    if not trailers and not tools:
        print("  no tooling trailer and no tool named in any commit message")

    tracked = [p for p in git("ls-files").strip().split("\n") if p]
    flagged: list[str] = []
    for rel in tracked:
        if rel in EXEMPT:
            continue
        f = ROOT / rel
        try:
            body = f.read_text(encoding="utf-8", errors="strict").lower()
        except (UnicodeDecodeError, OSError):
            continue
        for ph in PHRASES:
            if ph in body:
                flagged.append(f"{rel} contains {ph!r}")
    print(f"tracked files scanned: {len(tracked)}")
    if flagged:
        bad.extend(flagged[:10])
    else:
        print("  no generated-prose marker in any tracked file")

    if bad:
        print()
        for b in bad:
            print("FAIL: " + b)
        return 1
    print("PASS: one author, no tooling trailers, no generated-prose markers")
    return 0


if __name__ == "__main__":
    sys.exit(main())
